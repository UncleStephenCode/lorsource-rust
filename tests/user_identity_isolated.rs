    fn vValidateDisposableIdentityDatabase(
        sCurrentDatabase: &str,
        sExpectedDatabase: &str,
    ) -> anyhow::Result<()> {
        anyhow::ensure!(
            sCurrentDatabase == sExpectedDatabase,
            "connected database {sCurrentDatabase:?} does not match LOR_USER_IDENTITY_DB_INTEGRATION_EXPECT_DATABASE {sExpectedDatabase:?}"
        );

        let sLower = sCurrentDatabase.to_ascii_lowercase();
        let bProtectedToken = sLower
            .split(|cCharacter: char| !cCharacter.is_ascii_alphanumeric())
            .any(|sToken| matches!(sToken, "live" | "prod" | "production"));
        anyhow::ensure!(
            !matches!(sLower.as_str(), "lor" | "postgres")
                && !sLower.starts_with("template")
                && !bProtectedToken,
            "refusing to run the identity contract against protected database {sCurrentDatabase:?}"
        );
        anyhow::ensure!(
            sLower.starts_with("lorsource_identity_test_"),
            "disposable identity database name must start with lorsource_identity_test_; got {sCurrentDatabase:?}"
        );
        Ok(())
    }

    async fn vExecute(oPool: &PgPool, sSql: &str) -> anyhow::Result<()> {
        // Dynamic statements contain only the UUID-hex schema generated by
        // this test. No fixture, environment, or request value enters them.
        sqlx::query(sqlx::AssertSqlSafe(sSql.to_owned()))
            .execute(oPool)
            .await?;
        Ok(())
    }

